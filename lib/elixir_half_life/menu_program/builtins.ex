  @table @fte_names
         |> Enum.reverse()
         |> Enum.filter(fn {_name, number} -> Map.has_key?(@numbered, number) end)
         |> Map.new(fn {name, number} -> {name, Map.fetch!(@numbered, number)} end)
         |> Map.merge(@numbered)

  @doc "Whether builtin `builtin` (a menu number or a name) runs something."
  @spec known?(integer() | String.t() | nil) :: boolean()
  def known?(builtin) do
    case Map.get(@table, builtin) do
      {Server, :call, key} -> Server.known?(key)
      {Client, :call, key} -> Client.known?(key)
      {_module, _function, _key} -> true
      nil -> false
    end
  end

  @doc "Run builtin `builtin`, a menu number or a name, with `argc` arguments."
  @spec call(map(), integer() | String.t(), non_neg_integer()) :: map()
  def call(host, builtin, argc) do
    case Map.get(@table, builtin) do
      {module, function, key} ->
        apply(module, function, [host, key, argc])

      nil ->
        raise Exec.Error,
              "\nBuiltin #{number(builtin)}:#{name(builtin)} not implemented.\nMenu is not compatible."
    end
  end

  defp number(builtin) when is_integer(builtin), do: builtin
  defp number(_builtin), do: 0

  defp name(builtin) when is_binary(builtin), do: builtin
  defp name(builtin), do: Map.get(@names, builtin, "?unknown?")
end
